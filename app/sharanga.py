def calculate_scale_factor(ortho_file_path, chm_file_path):
    """
    Calculate the scale factor between the orthophoto and the CHM files based on their resolutions.

    Parameters:
    - ortho_file_path: str, path to the orthophoto file.
    - chm_file_path: str, path to the CHM file.

    Returns:
    - scale_factor: float, the scale factor to adjust coordinates from ortho to CHM.
    """
    with rasterio.open(ortho_file_path) as ortho_src, rasterio.open(
        chm_file_path
    ) as chm_src:
        # Assuming that the resolution is the same in both x and y directions
        ortho_res = ortho_src.res[0]  # resolution in meters per pixel for orthophoto
        chm_res = chm_src.res[0]  # resolution in meters per pixel for CHM

    # Calculate the scale factor from ortho to CHM
    scale_factor = ortho_res / chm_res
    return scale_factor


