"""Tree Girth"""


def calculate_girth(tree_object):
    # Assuming tree_object.segmented_image is a CHM segment where tree areas have height values and background is zero
    # Convert to a binary format suitable for findContours
    # Ensure that the values are boolean before multiplying by 255 to get uint8 type
    binary_image = (tree_object.segmented_image[:, :, 0] > 0).astype(np.uint8) * 255

    try:
        contours, _ = cv2.findContours(
            binary_image, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
        )
        if not contours or len(contours) == 0:
            raise ValueError("No contours found.")

        # Find the largest contour by area
        largest_contour = max(contours, key=cv2.contourArea)

        # Flatten the array if it's not 2D
        if largest_contour.ndim > 2:
            largest_contour = largest_contour.squeeze()

        # Calculate the pairwise distances between all points in the largest contour
        pairwise_distances = distance.cdist(
            largest_contour, largest_contour, "euclidean"
        )

        # The maximum distance between any two points in the contour is the diameter, from which we derive girth
        max_distance = np.max(pairwise_distances)

        # Convert distance to girth - this conversion factor may need to be adjusted for your specific data
        girth_meters = max_distance * pixel_to_meter

        tree_object.girth = girth_meters
        return girth_meters
    except Exception as e:
        print(f"An error occurred: {e}")
        tree_object.girth = 0
        return 0


