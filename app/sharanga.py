"""Converting CRS"""


def reproject_tif_to_4326(input_tif, output_tif):
    """
    Reproject a TIFF file to EPSG:4326 and overwrite the original file if requested.

    Args:
    input_tif (str): Path to the input GeoTIFF file.
    output_tif (str): Path to the output GeoTIFF file that will be in EPSG:4326.
    """
    with rasterio.open(input_tif) as src:
        # Check if the source CRS is already EPSG:4326
        if src.crs == CRS.from_epsg(4326):
            print("The TIFF is already in EPSG:4326.")
            return

        # Calculate the transformation and the new dimensions
        transform, width, height = calculate_default_transform(
            src.crs, CRS.from_epsg(4326), src.width, src.height, *src.bounds
        )

        # Define the kwargs for the output dataset
        kwargs = src.meta.copy()
        kwargs.update(
            {
                "crs": CRS.from_epsg(4326),
                "transform": transform,
                "width": width,
                "height": height,
            }
        )

        # Create a temporary file to write the reprojected data
        with NamedTemporaryFile(delete=False, suffix=".tif") as tmpfile:
            with rasterio.open(tmpfile.name, "w", **kwargs) as dst:
                for i in range(1, src.count + 1):  # For each band
                    reproject(
                        source=rasterio.band(src, i),
                        destination=rasterio.band(dst, i),
                        src_transform=src.transform,
                        src_crs=src.crs,
                        dst_transform=transform,
                        dst_crs=CRS.from_epsg(4326),
                        resampling=Resampling.nearest,
                    )

            # Replace the original file with the reprojected file
            os.replace(tmpfile.name, output_tif)
            print(f"Reprojected the TIFF to EPSG:4326 and saved as {output_tif}")


