def calculate_vegetation_index(tree_object, ortho_file_path, chm_to_ortho_scale_factor):
    try:
        # First, ensure that ortho_image is correctly defined here
        with rasterio.open(ortho_file_path) as src:
            ortho_image = src.read([1, 2, 3])  # Assuming RGB bands are 1, 2, 3
            ortho_image = np.moveaxis(ortho_image, 0, -1)  # Rearrange to HxWxC

        # Resize the tree's segmented mask from CHM to match the ortho image resolution
        mask_resized = resize(
            tree_object.segmented_image[:, :, 3] > 0,
            ortho_image.shape[:2],
            order=0,  # Use nearest-neighbor interpolation
            preserve_range=True,
            anti_aliasing=False,
        ).astype(bool)

        # Apply the resized mask to the ortho image to extract the tree region
        tree_region = (
            ortho_image * mask_resized[:, :, None]
        )  # Add new axis to match color channels

        # Extract red and green channels
        red_channel = tree_region[:, :, 0][mask_resized].astype(float)
        green_channel = tree_region[:, :, 1][mask_resized].astype(float)

        # Calculate MGRVI
        mgrvi = (green_channel**2 - red_channel**2) / (
            green_channel**2 + red_channel**2 + 1e-10
        )

        # Calculate mean MGRVI and classify health
        mean_mgrvi = np.mean(mgrvi)
        health_status = (
            "Poor"
            if mean_mgrvi < 0
            else "Moderately Healthy" if mean_mgrvi < 0.25 else "Healthy"
        )

        tree_object.health = health_status
        tree_object.mgrvi = mean_mgrvi

    except Exception as e:
        print(f"An error occurred: {e}")
        tree_object.health = "Unknown"
        tree_object.mgrvi = np.nan


