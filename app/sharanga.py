def read_bounding_boxes(file_path):
    with open(file_path, "r") as f:
        boxes = [line.strip().split() for line in f.readlines()]
    # Convert to float and ignore the class label for simplicity
    boxes = [(float(cx), float(cy), float(w), float(h)) for _, cx, cy, w, h in boxes]
    return boxes


def denormalize_bounding_boxes(boxes, image_width, image_height):
    denormalized_boxes = []
    for cx, cy, w, h in boxes:
        # Convert from normalized coordinates to pixel coordinates
        x_center_px = cx * image_width
        y_center_px = cy * image_height
        width_px = w * image_width
        height_px = h * image_height

        # Convert to (x_min, y_min, width, height)
        x_min = x_center_px - (width_px / 2)
        y_min = y_center_px - (height_px / 2)

        denormalized_boxes.append((x_min, y_min, width_px, height_px))
    return denormalized_boxes


