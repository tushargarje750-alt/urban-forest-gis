def grow_region(seed_point, labels, chm_cleaned, height_threshold, max_region_size):
    """
    Grow region based on decreasing height trend (slope analysis)
    Continues growing as long as the overall slope is decreasing from the seed point
    """
    from collections import deque
    import numpy as np
    
    # Queue for breadth-first search with path tracking
    queue = deque([(seed_point, [seed_point])])  # (current_point, path_from_seed)
    region_size = 0
    seed_height = chm_cleaned[seed_point]
    
    # Parameters for trend analysis
    min_path_length = 10  # Minimum points needed to calculate reliable slope
    slope_tolerance = 0.1  # Small positive slope tolerance for noise (meters per pixel)
    
    # Mark the seed point
    labels[seed_point] = labels[seed_point] if labels[seed_point] != 0 else 1
    
    while queue and region_size < max_region_size:
        current_point, path = queue.popleft()
        
        # Get all valid neighbors
        neighbors = get_neighbors(current_point, chm_cleaned.shape)
        
        for neighbor in neighbors:
            # Skip if already labeled or background
            if labels[neighbor] != 0 or chm_cleaned[neighbor] <= 0:
                continue
            
            # Create new path including this neighbor
            new_path = path + [neighbor]
            neighbor_height = chm_cleaned[neighbor]
            
            # For the first few pixels, just check basic height decrease
            if len(new_path) <= min_path_length:
                # Allow some tolerance for noise, but generally should be decreasing
                height_diff = seed_height - neighbor_height
                if height_diff >= -slope_tolerance:  # Small increase allowed for noise
                    labels[neighbor] = labels[seed_point]
                    queue.append((neighbor, new_path))
                    region_size += 1
            else:
                # Analyze slope trend for longer paths
                if should_continue_growing(new_path, chm_cleaned, slope_tolerance):
                    labels[neighbor] = labels[seed_point]
                    queue.append((neighbor, new_path))
                    region_size += 1
    
    return labels


def should_continue_growing(path, chm_cleaned, slope_tolerance):
    """
    Analyze if region should continue growing based on height trend
    Returns True if overall trend is decreasing (negative slope)
    """
    if len(path) < 3:
        return True
    
    # Get heights along the path
    heights = [chm_cleaned[point] for point in path]
    distances = list(range(len(heights)))  # Distance from seed point
    
    # Calculate slope using linear regression
    # Using simple least squares: slope = (n*Σxy - ΣxΣy) / (n*Σx² - (Σx)²)
    n = len(heights)
    sum_x = sum(distances)
    sum_y = sum(heights)
    sum_xy = sum(x * y for x, y in zip(distances, heights))
    sum_x_sq = sum(x * x for x in distances)
    
    # Calculate slope
    denominator = n * sum_x_sq - sum_x * sum_x
    if denominator == 0:  # Avoid division by zero
        return False
    
    slope = (n * sum_xy - sum_x * sum_y) / denominator
    
    # Continue growing if slope is negative (decreasing) or within tolerance
    return slope <= slope_tolerance

def calculate_recent_slope(path, chm_cleaned, window_size=5):
    """
    Calculate slope over the most recent points in the path
    This helps handle local noise while maintaining overall trend
    """
    if len(path) < 3:
        return -1  # Assume decreasing for short paths
    
    # Use only the most recent points
    recent_path = path[-window_size:] if len(path) >= window_size else path
    heights = [chm_cleaned[point] for point in recent_path]
    distances = list(range(len(heights)))
    
    # Simple slope calculation
    if len(heights) < 2:
        return -1
    
    # Linear regression slope
    n = len(heights)
    sum_x = sum(distances)
    sum_y = sum(heights)
    sum_xy = sum(x * y for x, y in zip(distances, heights))
    sum_x_sq = sum(x * x for x in distances)
    
    denominator = n * sum_x_sq - sum_x * sum_x
    if denominator == 0:
        return -1
    
    slope = (n * sum_xy - sum_x * sum_y) / denominator
    return slope


