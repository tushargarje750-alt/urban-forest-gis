def degrees_to_meters(degree, latitude):
    """
    Convert a measurement from degrees to meters, assuming spherical Earth.

    Args:
    degree (float): Measurement in degrees to convert.
    latitude (float): Latitude in degrees at which the conversion is relevant.

    Returns:
    float: Measurement in meters.
    """
    # Average radius of the Earth in kilometers
    earth_radius_km = 6371.0
    meters_per_degree = 2 * math.pi * earth_radius_km * 1000 / 360
    return degree * meters_per_degree * math.cos(math.radians(latitude))


