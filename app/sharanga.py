def pixel_to_geo(x, y, geotransform):
    """Convert pixel coordinates to georeferenced coordinates."""
    geo_x = geotransform[0] + geotransform[1] * x + geotransform[2] * y
    geo_y = geotransform[3] + geotransform[4] * x + geotransform[5] * y
    return (geo_x, geo_y)


def contours_to_georeferenced_polygons_wkt(segmented_image, geotransform, precision=10):
    """Converts contours found in a segmented image to high-precision WKT georeferenced polygons."""
    contours, _ = cv2.findContours(
        segmented_image, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
    )

    wkt_polygons = []
    valid_data_found = False  # Flag to check if any valid polygons were processed

    for contour in contours:
        if len(contour) >= 4:
            valid_data_found = True
            geo_points = [
                pixel_to_geo(point[0][0], point[0][1], geotransform)
                for point in contour
            ]
            # Ensure the polygon is closed
            if geo_points[0] != geo_points[-1]:
                geo_points.append(geo_points[0])

            poly = Polygon(geo_points)
            wkt_polygons.append(dumps(poly, rounding_precision=precision))

    if not valid_data_found:
        print("No valid data to process. Skipping.")
        return None  # Or return wkt_polygons which would be empty

    return wkt_polygons


