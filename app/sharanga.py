# Function to get 8-connected neighbors
def get_neighbors(point, shape):
    y, x = point
    neighbors = [
        (y - 1, x - 1),
        (y - 1, x),
        (y - 1, x + 1),
        (y, x - 1),
        (y, x + 1),
        (y + 1, x - 1),
        (y + 1, x),
        (y + 1, x + 1),
    ]
    return [n for n in neighbors if 0 <= n[0] < shape[0] and 0 <= n[1] < shape[1]]


